import { cp, mkdir, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const root = resolve(process.cwd());
const source = resolve(root, 'apps/web');
const target = resolve(root, 'dist');
await rm(target, { recursive: true, force: true });
await mkdir(target, { recursive: true });
await cp(source, target, { recursive: true });
await writeFile(resolve(target, 'deployment.json'), `${JSON.stringify({ app: 'rendezvue', market: 'netherlands', audience: 'adult-muslim-community-student-first', education: ['mbo','hbo','wo'], lifeStages: ['student','recentGraduate','employed','selfEmployed','jobSeeking','other'], languages: ['nl','en'], target: 'huggingface-static-space', version: '0.3.0-alpha.1', portraitMode: 'browser-local-privacy-filter-grid', interactionMode: 'local-concept-pilot' }, null, 2)}\n`, 'utf8');
console.log('Static Space build written to dist/.');

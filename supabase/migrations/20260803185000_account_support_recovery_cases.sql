-- WP-065D: service-only support cases for account recovery investigation.
-- This migration does not merge accounts, mutate Auth identities, restore access,
-- delete data or activate any retention policy.

do $$ begin
  create type public.account_support_case_kind as enum (
    'duplicate_account',
    'mailbox_access_loss'
  );
exception when duplicate_object then null; end $$;

do $$ begin
  create type public.account_support_case_state as enum (
    'open',
    'evidence_pending',
    'under_review',
    'escalated',
    'resolved',
    'rejected',
    'closed'
  );
exception when duplicate_object then null; end $$;

create table if not exists public.account_support_cases (
  id uuid primary key default gen_random_uuid(),
  kind public.account_support_case_kind not null,
  state public.account_support_case_state not null default 'open',
  primary_user_id uuid references auth.users(id) on delete set null,
  related_user_id uuid references auth.users(id) on delete set null,
  external_reference text not null unique,
  evidence_references text[] not null default '{}',
  assigned_to text,
  resolution_code text,
  opened_by text not null,
  opened_at timestamptz not null default timezone('utc', now()),
  state_changed_at timestamptz not null default timezone('utc', now()),
  closed_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint account_support_external_reference_length
    check (char_length(external_reference) between 1 and 160),
  constraint account_support_external_reference_opaque
    check (position('@' in external_reference) = 0),
  constraint account_support_opened_by_length
    check (char_length(opened_by) between 1 and 160),
  constraint account_support_opened_by_opaque
    check (position('@' in opened_by) = 0),
  constraint account_support_assigned_to_length
    check (assigned_to is null or char_length(assigned_to) between 1 and 160),
  constraint account_support_assigned_to_opaque
    check (assigned_to is null or position('@' in assigned_to) = 0),
  constraint account_support_resolution_length
    check (resolution_code is null or char_length(resolution_code) between 1 and 120),
  constraint account_support_evidence_count
    check (cardinality(evidence_references) <= 20),
  constraint account_support_distinct_accounts
    check (primary_user_id is null or related_user_id is null or primary_user_id <> related_user_id),
  constraint account_support_kind_accounts
    check (
      (kind = 'duplicate_account' and primary_user_id is not null and related_user_id is not null)
      or
      (kind = 'mailbox_access_loss' and primary_user_id is not null and related_user_id is null)
    ),
  constraint account_support_terminal_resolution
    check (
      state not in ('resolved', 'rejected', 'closed')
      or nullif(trim(resolution_code), '') is not null
    ),
  constraint account_support_closed_at_state
    check ((state = 'closed') = (closed_at is not null))
);

create table if not exists public.account_support_case_events (
  id bigint generated by default as identity primary key,
  case_id uuid not null references public.account_support_cases(id) on delete cascade,
  event_type text not null check (event_type in ('opened', 'state_transition')),
  from_state public.account_support_case_state,
  to_state public.account_support_case_state not null,
  operator_reference text not null,
  resolution_code text,
  evidence_count smallint not null default 0 check (evidence_count between 0 and 20),
  created_at timestamptz not null default timezone('utc', now()),
  constraint account_support_event_operator_length
    check (char_length(operator_reference) between 1 and 160),
  constraint account_support_event_operator_opaque
    check (position('@' in operator_reference) = 0),
  constraint account_support_event_resolution_length
    check (resolution_code is null or char_length(resolution_code) between 1 and 120),
  constraint account_support_event_states
    check (
      (event_type = 'opened' and from_state is null and to_state = 'open')
      or
      (event_type = 'state_transition' and from_state is not null and from_state <> to_state)
    )
);

create index if not exists account_support_cases_state_time_idx
on public.account_support_cases (state, state_changed_at);

create index if not exists account_support_cases_primary_idx
on public.account_support_cases (primary_user_id, state)
where primary_user_id is not null;

create index if not exists account_support_cases_related_idx
on public.account_support_cases (related_user_id, state)
where related_user_id is not null;

create index if not exists account_support_case_events_case_time_idx
on public.account_support_case_events (case_id, created_at, id);

create trigger account_support_cases_touch_updated_at
before update on public.account_support_cases
for each row execute function public.touch_updated_at();

create or replace function public.validate_account_support_references(
  p_external_reference text,
  p_operator_reference text,
  p_evidence_references text[]
)
returns void
language plpgsql
immutable
security definer
set search_path = public
as $$
declare
  v_reference text;
begin
  if nullif(trim(p_external_reference), '') is null
     or char_length(trim(p_external_reference)) > 160
     or position('@' in p_external_reference) > 0 then
    raise exception 'invalid opaque external reference';
  end if;

  if nullif(trim(p_operator_reference), '') is null
     or char_length(trim(p_operator_reference)) > 160
     or position('@' in p_operator_reference) > 0 then
    raise exception 'invalid opaque operator reference';
  end if;

  if cardinality(coalesce(p_evidence_references, '{}')) > 20 then
    raise exception 'too many evidence references';
  end if;

  foreach v_reference in array coalesce(p_evidence_references, '{}') loop
    if nullif(trim(v_reference), '') is null
       or char_length(trim(v_reference)) > 240
       or position('@' in v_reference) > 0 then
      raise exception 'invalid opaque evidence reference';
    end if;
  end loop;
end;
$$;

create or replace function public.open_account_support_case(
  p_kind public.account_support_case_kind,
  p_primary_user_id uuid,
  p_related_user_id uuid,
  p_external_reference text,
  p_operator_reference text,
  p_evidence_references text[] default '{}'
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_case_id uuid;
  v_evidence text[] := coalesce(p_evidence_references, '{}');
begin
  perform public.validate_account_support_references(
    p_external_reference,
    p_operator_reference,
    v_evidence
  );

  if p_kind = 'duplicate_account' then
    if p_primary_user_id is null or p_related_user_id is null or p_primary_user_id = p_related_user_id then
      raise exception 'duplicate-account case requires two distinct accounts';
    end if;
  elsif p_kind = 'mailbox_access_loss' then
    if p_primary_user_id is null or p_related_user_id is not null then
      raise exception 'mailbox-access-loss case requires one account';
    end if;
  else
    raise exception 'unsupported support case kind';
  end if;

  insert into public.account_support_cases (
    kind,
    primary_user_id,
    related_user_id,
    external_reference,
    evidence_references,
    assigned_to,
    opened_by
  ) values (
    p_kind,
    p_primary_user_id,
    p_related_user_id,
    trim(p_external_reference),
    v_evidence,
    trim(p_operator_reference),
    trim(p_operator_reference)
  )
  returning id into v_case_id;

  insert into public.account_support_case_events (
    case_id,
    event_type,
    from_state,
    to_state,
    operator_reference,
    evidence_count
  ) values (
    v_case_id,
    'opened',
    null,
    'open',
    trim(p_operator_reference),
    cardinality(v_evidence)
  );

  insert into public.audit_events (
    actor_type,
    event_type,
    entity_type,
    entity_id,
    payload
  ) values (
    'service',
    'account_support_case_opened',
    'account_support_case',
    v_case_id::text,
    jsonb_build_object(
      'kind', p_kind::text,
      'state', 'open',
      'evidence_count', cardinality(v_evidence)
    )
  );

  return v_case_id;
end;
$$;

create or replace function public.transition_account_support_case(
  p_case_id uuid,
  p_expected_state public.account_support_case_state,
  p_new_state public.account_support_case_state,
  p_operator_reference text,
  p_resolution_code text default null,
  p_evidence_references text[] default null
)
returns public.account_support_case_state
language plpgsql
security definer
set search_path = public
as $$
declare
  v_case public.account_support_cases%rowtype;
  v_resolution text := nullif(trim(p_resolution_code), '');
  v_evidence text[];
  v_allowed boolean := false;
begin
  select * into v_case
  from public.account_support_cases
  where id = p_case_id
  for update;

  if not found then
    raise exception 'support case not found';
  end if;
  if v_case.state <> p_expected_state then
    raise exception 'stale support case state';
  end if;
  if p_new_state = v_case.state then
    raise exception 'support case state must change';
  end if;

  v_allowed := case v_case.state
    when 'open' then p_new_state in ('evidence_pending', 'under_review', 'rejected')
    when 'evidence_pending' then p_new_state in ('under_review', 'rejected')
    when 'under_review' then p_new_state in ('evidence_pending', 'escalated', 'resolved', 'rejected')
    when 'escalated' then p_new_state in ('under_review', 'resolved', 'rejected')
    when 'resolved' then p_new_state = 'closed'
    when 'rejected' then p_new_state = 'closed'
    else false
  end;

  if not v_allowed then
    raise exception 'invalid support case transition';
  end if;

  if p_new_state in ('resolved', 'rejected') and v_resolution is null then
    raise exception 'resolution code required';
  end if;
  if p_new_state = 'closed' and coalesce(v_resolution, v_case.resolution_code) is null then
    raise exception 'resolution code required before closing';
  end if;

  v_evidence := case
    when p_evidence_references is null then v_case.evidence_references
    else p_evidence_references
  end;

  perform public.validate_account_support_references(
    v_case.external_reference,
    p_operator_reference,
    v_evidence
  );

  update public.account_support_cases
  set state = p_new_state,
      evidence_references = v_evidence,
      assigned_to = trim(p_operator_reference),
      resolution_code = coalesce(v_resolution, resolution_code),
      state_changed_at = timezone('utc', now()),
      closed_at = case when p_new_state = 'closed' then timezone('utc', now()) else null end
  where id = p_case_id;

  insert into public.account_support_case_events (
    case_id,
    event_type,
    from_state,
    to_state,
    operator_reference,
    resolution_code,
    evidence_count
  ) values (
    p_case_id,
    'state_transition',
    v_case.state,
    p_new_state,
    trim(p_operator_reference),
    v_resolution,
    cardinality(v_evidence)
  );

  insert into public.audit_events (
    actor_type,
    event_type,
    entity_type,
    entity_id,
    payload
  ) values (
    'service',
    'account_support_case_transitioned',
    'account_support_case',
    p_case_id::text,
    jsonb_build_object(
      'from_state', v_case.state::text,
      'to_state', p_new_state::text,
      'resolution_code', v_resolution,
      'evidence_count', cardinality(v_evidence)
    )
  );

  return p_new_state;
end;
$$;


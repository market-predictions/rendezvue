-- WP-070A — moderation intake and triage foundation.
--
-- Existing participant-facing report submission remains authoritative. This
-- migration adds a service-only operational queue and controlled case workflow;
-- it does not execute suspension, banning, deletion or any other enforcement.

alter table public.moderation_cases
  add column if not exists version integer not null default 1,
  add column if not exists assigned_operator_ref text,
  add column if not exists claimed_at timestamptz,
  add column if not exists triage_due_at timestamptz,
  add column if not exists last_activity_at timestamptz,
  add column if not exists closed_at timestamptz;

alter table public.moderation_cases
  add constraint moderation_cases_version_positive check (version > 0),
  add constraint moderation_cases_operator_ref_shape check (
    assigned_operator_ref is null
    or assigned_operator_ref ~ '^[A-Za-z0-9][A-Za-z0-9:_-]{2,95}$'
  );

create unique index if not exists moderation_cases_source_report_unique_idx
  on public.moderation_cases (source_report_id)
  where source_report_id is not null;

create index if not exists moderation_cases_queue_idx
  on public.moderation_cases (status, priority, triage_due_at, created_at);

create index if not exists safety_reports_queue_idx
  on public.safety_reports (status, severity, created_at);

create table if not exists public.moderation_case_events (
  id bigint generated by default as identity primary key,
  case_id uuid not null references public.moderation_cases(id) on delete cascade,
  case_version integer not null check (case_version > 0),
  event_type text not null check (event_type in ('case_opened', 'claimed', 'unclaimed', 'status_transition')),
  actor_ref text not null check (actor_ref ~ '^[A-Za-z0-9][A-Za-z0-9:_-]{2,95}$'),
  from_status public.moderation_state,
  to_status public.moderation_state,
  note text,
  metadata jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default timezone('utc', now()),
  constraint moderation_case_event_note_length check (note is null or char_length(note) <= 2000)
);

create index if not exists moderation_case_events_case_time_idx
  on public.moderation_case_events (case_id, occurred_at, id);

alter table public.moderation_case_events enable row level security;

create or replace function public.moderation_priority_for_severity(p_severity public.report_severity)
returns smallint
language sql
immutable
strict
set search_path = public
as $$
  select case p_severity
    when 'critical' then 1
    when 'high' then 2
    when 'medium' then 3
    else 4
  end::smallint;
$$;

create or replace function public.moderation_triage_target_for_severity(p_severity public.report_severity)
returns interval
language sql
immutable
strict
set search_path = public
as $$
  select case p_severity
    when 'critical' then interval '15 minutes'
    when 'high' then interval '2 hours'
    when 'medium' then interval '24 hours'
    else interval '72 hours'
  end;
$$;

create or replace function public.prepare_moderation_case_metadata()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_severity public.report_severity;
  v_report_created_at timestamptz;
begin
  new.version := coalesce(new.version, 1);
  new.last_activity_at := coalesce(new.last_activity_at, new.updated_at, new.created_at, timezone('utc', now()));

  if new.source_report_id is not null then
    select severity, created_at
      into v_severity, v_report_created_at
    from public.safety_reports
    where id = new.source_report_id;

    if found then
      if new.triage_due_at is null then
        new.triage_due_at := v_report_created_at + public.moderation_triage_target_for_severity(v_severity);
      end if;
      if new.priority = 3 and v_severity <> 'medium' then
        new.priority := public.moderation_priority_for_severity(v_severity);
      end if;
    end if;
  end if;

  return new;
end;
$$;

create or replace function public.record_moderation_case_opened()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.moderation_case_events (
    case_id, case_version, event_type, actor_ref, from_status, to_status, metadata
  ) values (
    new.id,
    new.version,
    'case_opened',
    'system:report-intake',
    null,
    new.status,
    jsonb_build_object('priority', new.priority)
  );
  return new;
end;
$$;

drop trigger if exists moderation_cases_prepare_metadata on public.moderation_cases;
create trigger moderation_cases_prepare_metadata
before insert on public.moderation_cases
for each row execute function public.prepare_moderation_case_metadata();

drop trigger if exists moderation_cases_record_opened on public.moderation_cases;
create trigger moderation_cases_record_opened
after insert on public.moderation_cases
for each row execute function public.record_moderation_case_opened();

-- Backfill the operational metadata for cases that predate WP-070A.
update public.moderation_cases c
set
  version = greatest(c.version, 1),
  triage_due_at = coalesce(
    c.triage_due_at,
    r.created_at + public.moderation_triage_target_for_severity(r.severity)
  ),
  last_activity_at = coalesce(c.last_activity_at, c.updated_at, c.created_at)
from public.safety_reports r
where c.source_report_id = r.id;

insert into public.moderation_case_events (
  case_id, case_version, event_type, actor_ref, from_status, to_status, metadata, occurred_at
)
select
  c.id,
  c.version,
  'case_opened',
  'system:wp070a-migration',
  null,
  c.status,
  jsonb_build_object('priority', c.priority, 'historical_case', true),
  c.created_at
from public.moderation_cases c
where not exists (
  select 1 from public.moderation_case_events e where e.case_id = c.id
);

create or replace function public.list_moderation_queue(p_limit integer default 100)
returns table (
  report_id uuid,
  case_id uuid,
  subject_user_id uuid,
  category text,
  severity public.report_severity,
  report_status public.moderation_state,
  case_status public.moderation_state,
  priority smallint,
  assigned_operator_ref text,
  case_version integer,
  report_created_at timestamptz,
  triage_due_at timestamptz,
  overdue boolean,
  description_preview text
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_limit is null or p_limit < 1 or p_limit > 200 then
    raise exception 'moderation queue limit must be between 1 and 200';
  end if;

  return query
  select
    r.id,
    c.id,
    r.subject_user_id,
    r.category,
    r.severity,
    r.status,
    c.status,
    coalesce(c.priority, public.moderation_priority_for_severity(r.severity)),
    c.assigned_operator_ref,
    coalesce(c.version, 0),
    r.created_at,
    coalesce(c.triage_due_at, r.created_at + public.moderation_triage_target_for_severity(r.severity)),
    timezone('utc', now()) > coalesce(c.triage_due_at, r.created_at + public.moderation_triage_target_for_severity(r.severity)),
    case when r.description is null then null else left(r.description, 500) end
  from public.safety_reports r
  left join public.moderation_cases c on c.source_report_id = r.id
  where r.status not in ('dismissed', 'closed')
    and (c.id is null or c.status not in ('dismissed', 'closed'))
  order by
    coalesce(c.priority, public.moderation_priority_for_severity(r.severity)) asc,
    coalesce(c.triage_due_at, r.created_at + public.moderation_triage_target_for_severity(r.severity)) asc,
    r.created_at asc,
    r.id asc
  limit p_limit;
end;
$$;

create or replace function public.claim_moderation_report(
  p_report_id uuid,
  p_operator_ref text,
  p_expected_case_version integer default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_report public.safety_reports%rowtype;
  v_case public.moderation_cases%rowtype;
  v_case_id uuid;
  v_new_version integer;
  v_now timestamptz := timezone('utc', now());
begin
  if p_operator_ref is null or p_operator_ref !~ '^[A-Za-z0-9][A-Za-z0-9:_-]{2,95}$' then
    raise exception 'invalid moderation operator reference';
  end if;
  if p_expected_case_version is not null and p_expected_case_version < 1 then
    raise exception 'invalid expected moderation case version';
  end if;

  select * into v_report
  from public.safety_reports
  where id = p_report_id
  for update;
  if not found then raise exception 'moderation report not found'; end if;
  if v_report.status in ('dismissed', 'closed') then
    raise exception 'moderation report already resolved';
  end if;

  select * into v_case
  from public.moderation_cases
  where source_report_id = p_report_id
  for update;

  if found then
    if p_expected_case_version is not null and v_case.version <> p_expected_case_version then
      raise exception 'stale moderation case version';
    end if;
    if v_case.status not in ('open', 'triage', 'investigating') then
      raise exception 'moderation case is not claimable';
    end if;
    if v_case.assigned_operator_ref is not null and v_case.assigned_operator_ref <> p_operator_ref then
      raise exception 'moderation case already claimed';
    end if;
    if v_case.assigned_operator_ref = p_operator_ref then
      return v_case.id;
    end if;

    update public.moderation_cases
    set
      assigned_operator_ref = p_operator_ref,
      claimed_at = v_now,
      status = case when status = 'open' then 'triage'::public.moderation_state else status end,
      last_activity_at = v_now,
      version = version + 1
    where id = v_case.id
    returning id, version into v_case_id, v_new_version;
  else
    if p_expected_case_version is not null then
      raise exception 'stale moderation case version';
    end if;

    insert into public.moderation_cases (
      subject_user_id,
      source_report_id,
      status,
      priority,
      assigned_operator_ref,
      claimed_at,
      triage_due_at,
      last_activity_at
    ) values (
      v_report.subject_user_id,
      v_report.id,
      'triage',
      public.moderation_priority_for_severity(v_report.severity),
      p_operator_ref,
      v_now,
      v_report.created_at + public.moderation_triage_target_for_severity(v_report.severity),
      v_now
    ) returning id, version into v_case_id, v_new_version;
  end if;

  update public.safety_reports
  set status = 'triage'
  where id = p_report_id and status = 'open';

  insert into public.moderation_case_events (
    case_id, case_version, event_type, actor_ref, from_status, to_status, metadata
  ) values (
    v_case_id,
    v_new_version,
    'claimed',
    p_operator_ref,
    coalesce(v_case.status, 'open'::public.moderation_state),
    'triage',
    jsonb_build_object('severity', v_report.severity, 'priority', public.moderation_priority_for_severity(v_report.severity))
  );

  insert into public.audit_events (
    actor_user_id, actor_type, event_type, subject_user_id, entity_type, entity_id, payload
  ) values (
    null,
    'service',
    'moderation_case_claimed',
    v_report.subject_user_id,
    'moderation_case',
    v_case_id::text,
    jsonb_build_object('severity', v_report.severity, 'priority', public.moderation_priority_for_severity(v_report.severity), 'case_version', v_new_version)
  );

  return v_case_id;
end;
$$;

create or replace function public.unclaim_moderation_case(
  p_case_id uuid,
  p_expected_version integer,
  p_operator_ref text,
  p_note text default null
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_case public.moderation_cases%rowtype;
  v_new_version integer;
  v_now timestamptz := timezone('utc', now());
begin
  if p_operator_ref is null or p_operator_ref !~ '^[A-Za-z0-9][A-Za-z0-9:_-]{2,95}$' then
    raise exception 'invalid moderation operator reference';
  end if;
  if p_note is not null and char_length(p_note) > 2000 then
    raise exception 'moderation note too long';
  end if;

  select * into v_case from public.moderation_cases where id = p_case_id for update;
  if not found then raise exception 'moderation case not found'; end if;
  if v_case.version <> p_expected_version then raise exception 'stale moderation case version'; end if;
  if v_case.assigned_operator_ref is distinct from p_operator_ref then
    raise exception 'moderation case is not claimed by operator';
  end if;
  if v_case.status not in ('triage', 'investigating') then
    raise exception 'moderation case cannot be unclaimed in current state';
  end if;

  update public.moderation_cases
  set assigned_operator_ref = null,
      claimed_at = null,
      last_activity_at = v_now,
      version = version + 1
  where id = p_case_id
  returning version into v_new_version;

  insert into public.moderation_case_events (
    case_id, case_version, event_type, actor_ref, from_status, to_status, note
  ) values (
    p_case_id, v_new_version, 'unclaimed', p_operator_ref, v_case.status, v_case.status,
    nullif(trim(p_note), '')
  );

  insert into public.audit_events (
    actor_user_id, actor_type, event_type, subject_user_id, entity_type, entity_id, payload
  ) values (
    null, 'service', 'moderation_case_unclaimed', v_case.subject_user_id,
    'moderation_case', p_case_id::text, jsonb_build_object('case_version', v_new_version)
  );

  return v_new_version;
end;
$$;

create or replace function public.transition_moderation_case(
  p_case_id uuid,
  p_expected_version integer,
  p_expected_status public.moderation_state,
  p_new_status public.moderation_state,
  p_operator_ref text,
  p_decision_code text default null,
  p_note text default null
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_case public.moderation_cases%rowtype;
  v_new_version integer;
  v_now timestamptz := timezone('utc', now());
  v_allowed boolean := false;
  v_effective_decision text;
begin
  if p_operator_ref is null or p_operator_ref !~ '^[A-Za-z0-9][A-Za-z0-9:_-]{2,95}$' then
    raise exception 'invalid moderation operator reference';
  end if;
  if p_note is not null and char_length(p_note) > 2000 then
    raise exception 'moderation note too long';
  end if;
  if p_decision_code is not null and p_decision_code !~ '^[a-z0-9][a-z0-9_:-]{2,79}$' then
    raise exception 'invalid moderation decision code';
  end if;

  select * into v_case from public.moderation_cases where id = p_case_id for update;
  if not found then raise exception 'moderation case not found'; end if;
  if v_case.version <> p_expected_version then raise exception 'stale moderation case version'; end if;
  if v_case.status <> p_expected_status then raise exception 'stale moderation case state'; end if;
  if v_case.assigned_operator_ref is distinct from p_operator_ref then
    raise exception 'moderation case is not claimed by operator';
  end if;

  v_allowed :=
       (v_case.status = 'open' and p_new_status = 'triage')
    or (v_case.status = 'triage' and p_new_status in ('investigating', 'dismissed'))
    or (v_case.status = 'investigating' and p_new_status = 'dismissed')
    or (v_case.status = 'dismissed' and p_new_status = 'closed');

  if not v_allowed then
    raise exception 'invalid WP-070A moderation case transition';
  end if;

  v_effective_decision := coalesce(nullif(trim(p_decision_code), ''), v_case.decision_code);
  if p_new_status in ('dismissed', 'closed') and v_effective_decision is null then
    raise exception 'moderation decision code required';
  end if;

  update public.moderation_cases
  set
    status = p_new_status,
    decision_code = v_effective_decision,
    decision_reason = case
      when p_new_status in ('dismissed', 'closed') and nullif(trim(p_note), '') is not null then nullif(trim(p_note), '')
      else decision_reason
    end,
    closed_at = case when p_new_status = 'closed' then v_now else closed_at end,
    last_activity_at = v_now,
    version = version + 1
  where id = p_case_id
  returning version into v_new_version;

  update public.safety_reports
  set status = p_new_status
  where id = v_case.source_report_id;

  insert into public.moderation_case_events (
    case_id, case_version, event_type, actor_ref, from_status, to_status, note, metadata
  ) values (
    p_case_id,
    v_new_version,
    'status_transition',
    p_operator_ref,
    v_case.status,
    p_new_status,
    nullif(trim(p_note), ''),
    jsonb_build_object('decision_code', v_effective_decision)
  );

  insert into public.audit_events (
    actor_user_id, actor_type, event_type, subject_user_id, entity_type, entity_id, payload
  ) values (
    null,
    'service',
    'moderation_case_transitioned',
    v_case.subject_user_id,
    'moderation_case',
    p_case_id::text,
    jsonb_build_object('from_status', v_case.status, 'to_status', p_new_status, 'case_version', v_new_version)
  );

  return v_new_version;
end;
$$;

